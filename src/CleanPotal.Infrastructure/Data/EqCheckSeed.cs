    public static void Run(CleanPotalDbContext db)
    {
        if (db.EqCheckTemplates.Any()) return;
        var order = 0;
        foreach (var (code, name, units, rows) in Templates)
        {
            var t = new EqCheckTemplate { Code = code, Name = name, SortOrder = ++order, UpdatedBy = "기본값" };
            db.EqCheckTemplates.Add(t);
            db.SaveChanges();
            var i = 0;
            foreach (var r in rows)
                db.EqCheckItems.Add(new EqCheckItem
                {
                    TemplateId = t.Id, Cycle = r.C, SortOrder = ++i, Category = r.Cat, Name = r.N, Point = r.P, Spec = r.S,
                    InputType = r.T, Options = r.O, Fields = r.F, Unit = r.U, Min = r.Min, Max = r.Max, RunOnly = r.Run,
                });
            foreach (var u in units)
                if (!db.EqCheckUnits.Local.Any(x => x.Code == u) && !db.EqCheckUnits.Any(x => x.Code == u))
                    db.EqCheckUnits.Add(new EqCheckUnit { Code = u, TemplateId = t.Id });
        }
        db.SaveChanges();
        Console.WriteLine($"[seed] 체크시트(설비) 양식 {Templates.Length}종·항목 {Templates.Sum(t => t.Rows.Length)}개·호기 {Templates.Sum(t => t.Units.Length)}대");
    }
